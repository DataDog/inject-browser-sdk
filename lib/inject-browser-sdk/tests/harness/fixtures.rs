//! Real-world shaped documents, each written as the output it must produce under every strategy:
//! [`MARK`] marks where the snippet goes under both, [`OPEN`] and [`CLOSE`] where it goes under one
//! of them only, and a document without a mark for a strategy must come out of it untouched.

use inject_browser_sdk::injector::InjectionStrategy;

/// Where the snippet goes in a fixture's template under every strategy: the snippet the harness
/// injects.
pub const MARK: &str = "{{SNIPPET}}";
/// Where it goes under [`InjectionStrategy::HeadOpenTag`] only.
pub const OPEN: &str = "{{OPEN}}";
/// Where it goes under [`InjectionStrategy::HeadCloseTag`] only.
pub const CLOSE: &str = "{{CLOSE}}";

pub struct Fixture {
    pub name: &'static str,
    /// The expected output under every strategy, see [`Fixture::expected`].
    pub template: Vec<u8>,
}

impl Fixture {
    fn new(name: &'static str, template: impl Into<Vec<u8>>) -> Self {
        return Self {
            name,
            template: template.into(),
        };
    }

    /// The document the injector is given: the template without its marks.
    pub fn document(&self) -> Vec<u8> {
        return [MARK, OPEN, CLOSE]
            .iter()
            .fold(self.template.clone(), |template, mark| {
                return replace(&template, mark.as_bytes(), b"");
            });
    }

    /// The output `strategy` must produce: the template with the mark of that strategy standing for
    /// the snippet, the other one dropped.
    pub fn expected(&self, strategy: InjectionStrategy) -> Vec<u8> {
        let (own, other) = match strategy {
            InjectionStrategy::HeadOpenTag => (OPEN, CLOSE),
            InjectionStrategy::HeadCloseTag => (CLOSE, OPEN),
        };
        let expected = replace(&self.template, other.as_bytes(), b"");
        let expected = replace(&expected, own.as_bytes(), MARK.as_bytes());
        let marks = expected
            .windows(MARK.len())
            .filter(|window| return *window == MARK.as_bytes())
            .count();
        assert!(marks <= 1, "{}: more than one {strategy:?} mark", self.name);
        return expected;
    }
}

/// `bytes` with every `from` replaced by `to`.
fn replace(bytes: &[u8], from: &[u8], to: &[u8]) -> Vec<u8> {
    let mut replaced = Vec::with_capacity(bytes.len());
    let mut rest = bytes;
    while let Some(at) = rest
        .windows(from.len())
        .position(|window| return window == from)
    {
        replaced.extend_from_slice(&rest[..at]);
        replaced.extend_from_slice(to);
        rest = &rest[at + from.len()..];
    }
    replaced.extend_from_slice(rest);
    return replaced;
}

