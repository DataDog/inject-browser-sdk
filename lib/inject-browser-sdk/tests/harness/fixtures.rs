/// The markup fuzzing once found handled wrongly, each reduced to the construct at fault. In every
/// one an `X-UA-Compatible` meta follows the construct: whether the walk goes on past it shows in
/// where the snippet goes.
pub fn regressions() -> Vec<Fixture> {
    const XUA: &str = "<meta http-equiv=X-UA-Compatible content=IE=edge>";
    return vec![
        // The `in head` insertion mode closes the head on `</html>`, `</body>` and `</br>`, so the
        // walk stops there. lol_html keeps the head open without those elements open.
        Fixture::new(
            "html-end-tag-closes-head",
            format!("<html><head><meta charset=utf-8>{MARK}</html>{XUA}</head>"),
        ),
        Fixture::new(
            "body-end-tag-closes-head",
            format!("<html><head><meta charset=utf-8>{MARK}</body>{XUA}</head>"),
        ),
        Fixture::new(
            "br-end-tag-closes-head",
            format!("<html><head><meta charset=utf-8>{MARK}</br>{XUA}</head>"),
        ),
        Fixture::new(
            "html-end-tag-with-no-html-open",
            format!("<HEAD><META CHARSET=ISO-8859-1>{MARK}</HTML>{XUA}</HEAD>"),
        ),
        // A quote in an end tag's name is part of the name: `</x=">` ends at its `>`.
        Fixture::new(
            "quote-in-end-tag-name",
            format!("<html><head><meta charset=utf-8></x=\">{XUA}{MARK}\"></head>"),
        ),
        // A `/` between attributes starts a new one, so the `=` after it starts a name, not a value:
        // `<meta /=">` ends at its `>`.
        Fixture::new(
            "slash-before-equals-sign",
            format!("<html><head><meta charset=utf-8><meta /=\">{XUA}{MARK}\"></head>"),
        ),
        // Body content before the `<head>` tag: the browser ignores the tag, so nothing goes in.
        Fixture::new(
            "end-tag-of-element-before-head",
            format!("<div><head><meta charset=utf-8></div>{XUA}</head>"),
        ),
        // A stray `</div>` in a nested template closes neither template: what the outer one holds,
        // a charset meta included, stays inert.
        Fixture::new(
            "end-tag-in-nested-template",
            format!(
                "<html><head><template><template></div></template><meta charset=utf-8></template>{XUA}{MARK}</head>"
            ),
        ),
        // An empty unquoted attribute value on a raw text element, which lol_html 3.0 once
        // tokenized wrongly: the element ends at its end tag all the same.
        Fixture::new(
            "script-empty-attribute-value",
            format!("<html><head><script c=></script><meta charset=utf-8>{MARK}</head>"),
        ),
        Fixture::new(
            "title-empty-attribute-value",
            format!("<html><head><title c=></title><meta charset=utf-8>{MARK}</head>"),
        ),
        // Foreign content ends the walk. lol_html is not run on it: some makes 3.0.3 panic.
        Fixture::new(
            "foreign-content-in-head",
            format!("<html><head><meta charset=utf-8>{MARK}<svg><style></style></svg>{XUA}</head>"),
        ),
    ];
}
