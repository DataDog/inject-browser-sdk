//! Real-world shaped documents, each written as the output it must produce: `{{SNIPPET}}` marks
//! where the snippet goes, and a document without it must come out untouched.

/// Where the snippet must go in a fixture's template: the snippet the harness injects.
pub const MARK: &str = "{{SNIPPET}}";

pub struct Fixture {
    pub name: &'static str,
    /// The expected output; the document is this without [`MARK`].
    pub template: Vec<u8>,
}

impl Fixture {
    fn new(name: &'static str, template: impl Into<Vec<u8>>) -> Self {
        return Self {
            name,
            template: template.into(),
        };
    }

    /// The document the injector is given.
    pub fn document(&self) -> Vec<u8> {
        let mark = MARK.as_bytes();
        return match self
            .template
            .windows(mark.len())
            .position(|window| return window == mark)
        {
            Some(at) => [&self.template[..at], &self.template[at + mark.len()..]].concat(),
            None => self.template.clone(),
        };
    }
}

